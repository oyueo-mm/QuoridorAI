"""Cross-language checks: the Python engine must reproduce the TypeScript engine on every
fixture case (training/fixtures/engine_fixtures.json, generated by `npm run fixtures:engine`)."""

import json
from pathlib import Path

import numpy as np
import pytest

from quoridor_az import engine as E
from quoridor_az import features as F

FIXTURES = Path(__file__).resolve().parents[1] / 'fixtures' / 'engine_fixtures.json'
DATA = json.loads(FIXTURES.read_text(encoding='utf-8'))
CASES = DATA['cases']
CHECK_CODE = {'ok': 'o', 'game-over': 'g', 'no-walls-left': 'n', 'out-of-bounds': '?', 'overlap': 'x', 'blocks-path': 'b'}


def test_fixture_metadata():
    assert DATA['version'] == 1
    assert DATA['action_space_size'] == E.ACTION_SPACE_SIZE == 209
    assert len(CASES) > 400


def test_action_encoding_table_matches_typescript():
    for a in DATA['actions']:
        action = E.decode_action(a['index'])
        if a['type'] == 'move':
            assert action == E.Move(a['row'], a['col'])
        else:
            assert action == E.Wall(a['orientation'], a['row'], a['col'])
        assert E.encode_action(action) == a['index']
        assert E.format_action(action) == a['notation']


@pytest.mark.parametrize('case', CASES, ids=[c['name'] for c in CASES])
def test_engine_matches_typescript(case):
    s = E.state_from_dict(case['state'])
    assert E.state_to_dict(s) == case['state']

    # Legal actions: same set and same order.
    assert E.legal_action_indices(s) == case['legal']
    mask = F.legal_mask(s)
    assert mask.sum() == len(case['legal'])
    assert np.flatnonzero(mask).tolist() == sorted(case['legal'])

    # Every wall slot gives the same verdict.
    checks = ''.join(
        CHECK_CODE[E.check_wall_placement(s, E.Wall(o, r, c))] for o in ('h', 'v') for r in range(8) for c in range(8)
    )
    assert checks == case['wall_checks']

    # Shortest paths.
    d = [E.distance_to_row(s.h_walls, s.v_walls, s.pawns[p], E.goal_row(p)) for p in (0, 1)]
    assert d == case['distances']
    if s.winner is None:
        path = E.shortest_path(s.h_walls, s.v_walls, s.pawns[s.current_player], E.goal_row(s.current_player))
        assert len(path) == case['path_length']

    # Transitions.
    for t in case['transitions']:
        action = E.decode_action(t['action'])
        assert E.format_action(action) == t['notation']
        assert E.is_legal_action(s, action)
        assert E.state_to_dict(E.apply_action(s, action)) == t['next']

    # Canonical (player-to-move) action space and feature planes.
    assert sorted(F.canonical_action_index(a, s.current_player) for a in case['legal']) == case['canonical_legal']
    assert np.flatnonzero(F.canonical_legal_mask(s)).tolist() == case['canonical_legal']
    if 'planes' in case:
        planes = F.encode_state_planes(s)
        assert planes.shape == (F.NUM_FEATURE_PLANES, 9, 9)
        np.testing.assert_allclose(planes.reshape(-1), np.array(case['planes'], dtype=np.float32), atol=1e-6)


def test_terminal_states_have_no_actions():
    won = [c for c in CASES if c['state']['winner'] is not None]
    assert won
    for c in won:
        s = E.state_from_dict(c['state'])
        assert E.legal_actions(s) == []
        assert not F.legal_mask(s).any()
